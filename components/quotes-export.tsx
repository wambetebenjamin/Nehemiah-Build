'use client'

import { useState } from 'react'
import { Download, FileText, Loader2 } from 'lucide-react'
import { formatKES } from '@/lib/site'

export type QuoteSheet = {
  projectTitle: string
  projectId: string
  county: string
  budgetLabel: string
  postedOn: string
  homeowner: string
  quotes: Array<{
    contractorCompany: string
    trade: string
    amount: number
    timelineWeeks: number
    status: string
    headline: string
  }>
}

/**
 * PDF export of the comparison. The sheet below is real DOM that is rendered
 * off screen (never display: none, html2canvas can only paint what it can
 * lay out), styled with plain hex colours so the rasteriser never meets a colour
 * function it cannot parse. If the rasteriser still fails on a device, the button
 * falls back to the browser print dialogue, which produces the same sheet.
 */
export function QuotesExportButton({ sheet }: { sheet: QuoteSheet }) {
  const [busy, setBusy] = useState(false)
  const [message, setMessage] = useState<string | null>(null)

  const exportPdf = async () => {
    const node = document.getElementById('nb-quote-sheet')
    if (!node) return

    setBusy(true)
    setMessage(null)

    try {
      const [{ default: html2canvas }, { jsPDF }] = await Promise.all([
        import('html2canvas'),
        import('jspdf'),
      ])

      const canvas = await html2canvas(node, {
        scale: 2,
        backgroundColor: '#ffffff',
        useCORS: true,
        logging: false,
      })

      const pdf = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' })
      const pageWidth = pdf.internal.pageSize.getWidth()
      const pageHeight = pdf.internal.pageSize.getHeight()
      const margin = 24
      const maxWidth = pageWidth - margin * 2
      const maxHeight = pageHeight - margin * 2
      const ratio = canvas.height / canvas.width
      let width = maxWidth
      let height = width * ratio
      if (height > maxHeight) {
        height = maxHeight
        width = height / ratio
      }

      pdf.addImage(canvas.toDataURL('image/jpeg', 0.94), 'JPEG', margin, margin, width, height)
      pdf.setFont('helvetica', 'normal')
      pdf.setFontSize(7)
      pdf.setTextColor(108, 117, 125)
      pdf.text(
        `${sheet.projectTitle} | ${sheet.county} | generated by Nehemiah Build on ${new Date().toLocaleDateString(
          'en-KE',
        )}`,
        margin,
        pageHeight - 10,
      )
      pdf.save(`nehemiah-build-quotes-${sheet.projectId}.pdf`)
      setMessage('PDF downloaded. Nothing was uploaded anywhere: the file was built in your browser.')
    } catch {
      setMessage('The PDF could not be built on this device. Opening the print dialogue instead, choose Save as PDF.')
      window.print()
    } finally {
      setBusy(false)
    }
  }

  return (
    <>
      <div className="flex flex-col items-stretch gap-2 sm:flex-row sm:items-center sm:gap-4">
        <button
          type="button"
          onClick={() => void exportPdf()}
          disabled={busy}
          className="btn btn-outline inline-flex min-h-[44px] items-center justify-center gap-2 px-5 py-2 text-[13px]"
        >
          {busy ? (
            <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
          ) : (
            <Download className="h-4 w-4" aria-hidden="true" />
          )}
          {busy ? 'Building PDF' : 'Download PDF'}
        </button>
        {message ? (
          <p role="status" className="mb-0 flex items-start gap-2 text-[13px] leading-snug text-[color:var(--gray-dark)]">
            <FileText className="mt-0.5 h-4 w-4 shrink-0 text-[color:var(--nb-primary)]" aria-hidden="true" />
            {message}
          </p>
        ) : (
          <p className="mb-0 text-[13px] text-[color:var(--gray)]">
            Hand the sheet to anyone: it is the same table you are looking at, with the reference numbers.
          </p>
        )}
      </div>

      <div id="nb-quote-sheet" className="quote-sheet" aria-hidden="true">
        <p className="qs-brand">Nehemiah Build &middot; {sheet.county} &middot; quote comparison</p>
        <h2>{sheet.projectTitle}</h2>
        <div className="qs-meta">
          <span>
            <strong>Project reference:</strong> {sheet.projectId}
          </span>
          <span>
            <strong>Homeowner:</strong> {sheet.homeowner}
          </span>
          <span>
            <strong>Posted:</strong> {sheet.postedOn}
          </span>
          <span>
            <strong>Budget band:</strong> {sheet.budgetLabel}
          </span>
        </div>
        <table>
          <thead>
            <tr>
              <th>Contractor</th>
              <th>Trade</th>
              <th>Scope note</th>
              <th>Programme</th>
              <th>Amount</th>
              <th>Status</th>
            </tr>
          </thead>
          <tbody>
            {sheet.quotes.map((quote) => (
              <tr key={`${quote.contractorCompany}-${quote.amount}`}>
                <td>
                  <strong>{quote.contractorCompany}</strong>
                </td>
                <td>{quote.trade}</td>
                <td>{quote.headline}</td>
                <td>{quote.timelineWeeks} weeks</td>
                <td className="qs-num">{formatKES(quote.amount)}</td>
                <td>{quote.status}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className="qs-note">
          Amounts are contractor quotations in Kenya Shillings and exclude county approval fees, materials bought
          directly by the homeowner, and VAT unless the contractor states otherwise. Nehemiah Build is not a payment
          processor: milestone payments move between the homeowner and the contractor, and the platform keeps the
          approval record. Payment pending bank transfer confirmation.
        </p>
      </div>
    </>
  )
}
